    if images.ndim == 3:
        images = images[None, ...]

    type_dir = os.path.join(out_root, experiment_name, slugify(prompt_type))
    os.makedirs(type_dir, exist_ok=True)

    for idx, img in enumerate(images):
        pil_img = Image.fromarray(img.astype(np.uint8))
        out_path = os.path.join(type_dir, f"{idx}.png")
        pil_img.save(out_path)
