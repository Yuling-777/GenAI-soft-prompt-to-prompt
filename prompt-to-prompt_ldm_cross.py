def quadratic_slow_to_fast_scaler(t: int, power: float = 2.0):
    """
    Concave-down decay like the black curve:
    starts near 1, decreases slowly at first,
    then drops quickly near the end.
    """
    x = float(t) / float(num_steps)
    alpha = 1.0 - (x ** power)
    return float(np.clip(alpha, 0.0, 1.0))

def exp_decay_scaler(t: int, tau: float = 0.3):
    """Exponential: starts near 1, decays quickly then slowly."""
    x = float(t) / float(num_steps)
    return float(np.exp(-x / tau))

