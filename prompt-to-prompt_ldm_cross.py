def aggregate_attention_for_step(
    step_store: dict,
    res: int,
    from_where,
    is_cross: bool,
    select: int,
    num_prompts: int,
):
    out = []
    num_pixels = res ** 2
    for location in from_where:
        key = f"{location}_{'cross' if is_cross else 'self'}"
        if key not in step_store:
            continue
        for item in step_store[key]:
            if item.shape[1] == num_pixels:
                cross_maps = item.reshape(num_prompts, -1, res, res, item.shape[-1])[select]
                out.append(cross_maps)
    if not out:
        return None
    out = torch.cat(out, dim=0)
    out = out.sum(0) / out.shape[0]
    return out.cpu()


def plot_token_cross_attention_over_time(
    controller_with_history,
    experiment_name: str,
    prompts_pair,
    token_index: int,
    res: int = 16,
    from_where = ("down", "mid", "up"),
    prompt_index: int = 1,
    step_stride: int = 5,
):
    num_prompts = len(prompts_pair)
    images = []

    for step, step_store in enumerate(controller_with_history.step_history):
        if step % step_stride != 0:
            continue

        attn_map = aggregate_attention_for_step(
            step_store,
            res=res,
            from_where=from_where,
            is_cross=True,
            select=prompt_index,
            num_prompts=num_prompts,
        )
        if attn_map is None:
            continue

        token_map = attn_map[:, :, token_index]
        token_map = token_map.numpy()
        token_map = token_map - token_map.min()
        if token_map.max() > 0:
            token_map = token_map / token_map.max()
